"""Rebuild the static-page search index using only the Python standard library."""
from html.parser import HTMLParser
from pathlib import Path
import json,re
class PageText(HTMLParser):
    def __init__(self):
        super().__init__(); self.main=False; self.title=False; self.ignore=0; self.parts=[]; self.title_parts=[]
    def handle_starttag(self,tag,attrs):
        if tag=='main':self.main=True
        if tag=='title':self.title=True
        if tag in ('script','style','noscript'):self.ignore+=1
    def handle_endtag(self,tag):
        if tag=='main':self.main=False
        if tag=='title':self.title=False
        if tag in ('script','style','noscript'):self.ignore=max(0,self.ignore-1)
    def handle_data(self,data):
        if self.title:self.title_parts.append(data)
        if self.main and not self.ignore:self.parts.append(data)
root=Path(__file__).parent
records=[]
member_ids={p.stem for p in (root/'members').glob('*.json')}
for path in sorted(root.glob('*.html')):
    if path.name in ('project.html','search.html','member-login.html') or path.name.startswith('project-') or path.stem in member_ids:continue
    dom=PageText();dom.feed(path.read_text())
    title=' '.join(dom.title_parts).split(' — ADOPT')[0]
    text=re.sub(r'\s+',' ',' '.join(dom.parts)).strip()
    records.append({'title':title,'section':title,'url':path.name,'type':'Site page','text':text})
(root/'search-index.js').write_text('// Generated by build_search_index.py.\nwindow.ADOPT_SEARCH_INDEX = '+json.dumps(records,ensure_ascii=False,indent=2)+';\n')
print(f'Indexed {len(records)} static pages; projects, people and publications are indexed at runtime.')
